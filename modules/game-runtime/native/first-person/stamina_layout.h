inline bool MatchesStaminaLayout(
    const std::uint8_t* image,
    std::size_t size,
    std::uintptr_t loadedBase,
    const std::array<std::uint8_t, StaminaCallSize>& staminaCall = OriginalStaminaCall) {
    if (!MatchesClientPeIdentity(image, size) ||
        !MatchesStaminaRegistration(image, size, loadedBase)) return false;

    for (const auto& guard : GaugeGuards()) {
        if (guard.rva > size || guard.bytes.size() > size - guard.rva) return false;
        for (std::size_t index = 0; index < guard.bytes.size(); ++index) {
            const auto rva = guard.rva + index;
            std::uint8_t expected = guard.bytes[index];
            if (rva >= StaminaLayoutSite && rva < StaminaLayoutSite + staminaCall.size()) {
                expected = staminaCall[rva - StaminaLayoutSite];
            }
            if (image[rva] != expected) return false;
        }
    }
    return true;
}

